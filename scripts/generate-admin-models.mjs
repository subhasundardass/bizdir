import { readFile, writeFile } from 'node:fs/promises';
const labels = {
  app_user: 'Users',
  attribute: 'Attributes',
  business: 'Places',
  business_attribute: 'Place attributes',
  business_concept: 'Place categories',
  business_hours: 'Opening hours',
  business_media: 'Place media',
  business_subscription: 'Subscriptions',
  click_log: 'Click activity',
  concept: 'Categories & services',
  concept_alias: 'Category aliases',
  creator: 'Creators',
  lead: 'Leads',
  location: 'Locations',
  location_alias: 'Location aliases',
  payout: 'Payouts',
  review: 'Reviews',
  search_log: 'Search activity',
  attribute_alias: 'Attribute aliases',
  attribute_option: 'Attribute options',
  business_alias: 'Place aliases',
  business_claim: 'Ownership claims',
  business_closure: 'Special closures',
  concept_attribute: 'Category attributes',
  lead_status_history: 'Lead history',
  search_impression: 'Search impressions'
};
const schema = await readFile('prisma/schema/schema.prisma', 'utf8');
const models = [];
for (const match of schema.matchAll(/model (\w+) \{([\s\S]*?)\n\}/g)) {
  const [, name, body] = match;
  if (!labels[name]) continue;
  const fields = [];
  for (const line of body.split('\n')) {
    const field = line.match(
      /^\s+(\w+)\s+(String|Int|BigInt|Boolean|DateTime|Decimal|Json)(\?)?\s*(.*)$/
    );
    if (!field) continue;
    const [, name, type, nullable, attrs] = field;
    const def = attrs.match(/@default\(("[^"]*"|true|false|-?\d+(?:\.\d+)?)\)/);
    const generated =
      attrs.includes('@default(autoincrement())') ||
      ['created_at', 'updated_at', 'changed_at', 'name_norm'].includes(name) ||
      (match[1] === 'business' && ['rating', 'review_count'].includes(name));
    fields.push({
      name,
      type,
      required: !nullable,
      generated,
      primary: attrs.includes('@id'),
      ...(def ? { default: JSON.parse(def[1]) } : {}),
      ...(/@db.Date(?:\s|$)/.test(attrs) ? { dateOnly: true } : {}),
      ...(/@db.Time\(/.test(attrs) ? { timeOnly: true } : {})
    });
  }
  const compound = body.match(/@@id\(\[([^\]]+)\]/);
  let keys = compound
    ? compound[1].split(',').map((x) => x.trim())
    : fields.filter((f) => f.primary).map((f) => f.name);
  if (!keys.length) {
    const unique = body
      .split('\n')
      .find((l) => l.includes('@unique') && !l.trim().startsWith('@@'));
    if (unique) keys = [unique.trim().split(/\s+/)[0]];
  }
  if (!keys.length) throw new Error(`No record key defined for ${name}`);
  models.push({
    name,
    label: labels[name],
    fields,
    keys,
    readonly: ['click_log', 'search_log', 'search_impression', 'lead_status_history'].includes(name)
  });
}
if (models.length !== Object.keys(labels).length)
  throw new Error('Schema and admin resource catalog are out of sync.');
const types = `// Generated by scripts/generate-admin-models.mjs from prisma/schema/schema.prisma.\nexport type Field = {name:string;type:string;required:boolean;generated:boolean;primary:boolean;default?:string|number|boolean;dateOnly?:boolean;timeOnly?:boolean};\nexport type Model={name:string;label:string;fields:Field[];keys:string[];readonly:boolean};\n`;
await writeFile(
  'src/features/admin/models.ts',
  types + 'export const models: Model[] = ' + JSON.stringify(models, null, 2) + ';\n'
);
console.log(`Generated ${models.length} admin resource definitions.`);
